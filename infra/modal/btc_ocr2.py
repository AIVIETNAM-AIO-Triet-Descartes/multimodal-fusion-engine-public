class MountedVolumeTransport:
    """Bundle transport backed by the Volume mounted in this Modal container."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)

    def _resolve(self, remote: str) -> Path:
        target = (self.root / remote.lstrip("/")).resolve()
        if self.root.resolve() not in target.parents and target != self.root.resolve():
            raise ValueError(f"duong dan thoat Volume: {remote}")
        return target

    def put(self, local: Path, remote: str) -> None:
        target = self._resolve(remote)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(local, target)

    def get(self, remote: str, local: Path) -> None:
        source = self._resolve(remote)
        if not source.is_file():
            raise FileNotFoundError(remote)
        Path(local).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, local)

    def listdir(self, prefix: str) -> list[str]:
        base = self._resolve(prefix)
        if not base.is_dir():
            return []
        return sorted(
            "/" + path.relative_to(self.root).as_posix()
            for path in base.rglob("*")
            if path.is_file()
        )

    def exists(self, remote: str) -> bool:
        return self._resolve(remote).is_file()

    def sha256(self, remote: str) -> str | None:
        path = self._resolve(remote)
        if not path.is_file():
            return None
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            while chunk := handle.read(1 << 20):
                digest.update(chunk)
        return digest.hexdigest()


def _validate_zip(path: Path) -> None:
    try:
        with zipfile.ZipFile(path) as archive:
            if not archive.infolist():
                raise RuntimeError(f"{path}: ZIP rong")
    except zipfile.BadZipFile as err:
        raise RuntimeError(f"{path}: khong phai ZIP hoan chinh") from err


def _download(url: str, target: Path, expect_bytes: int | None = None) -> Path:
    if target.is_file() and (expect_bytes is None or target.stat().st_size == expect_bytes):
        _validate_zip(target)
        return target
    if target.exists():
        target.unlink()
    target.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "wget",
            "-q",
            "--show-progress",
            "-c",
            "--timeout=30",
            "--read-timeout=60",
            "--tries=20",
            "--waitretry=10",
            "--retry-connrefused",
            "-O",
            str(target),
            url,
        ],
        check=True,
    )
    if expect_bytes is not None and target.stat().st_size != expect_bytes:
        actual = target.stat().st_size
        target.unlink(missing_ok=True)
        raise RuntimeError(
            f"{target.name}: tai ve {actual:,} byte, cho doi {expect_bytes:,}. Da xoa."
        )
    _validate_zip(target)
    return target


def _extract_video(zip_path: Path, video_id: str, into: Path) -> tuple[Path, int]:
    out = into / video_id
    out.mkdir(parents=True, exist_ok=True)
    count = 0
    with zipfile.ZipFile(zip_path) as archive:
        for name in archive.namelist():
            parts = Path(name).parts
            if len(parts) < 2 or parts[-2] != video_id or name.endswith("/"):
                continue
            with archive.open(name) as source, (out / parts[-1]).open("wb") as target:
                shutil.copyfileobj(source, target, length=1 << 20)
            count += 1
    return out, count


def _extract_one_file(zip_path: Path, inner_suffix: str, destination: Path) -> Path:
    with zipfile.ZipFile(zip_path) as archive:
        matches = [name for name in archive.namelist() if name.endswith(inner_suffix)]
        if len(matches) != 1:
            raise FileNotFoundError(
                f"{inner_suffix}: cho doi dung 1 file trong {zip_path.name}, thay {len(matches)}"
            )
        destination.parent.mkdir(parents=True, exist_ok=True)
        with archive.open(matches[0]) as source, destination.open("wb") as target:
            shutil.copyfileobj(source, target)
    return destination


def _probe_dual_gpu() -> None:
    # Same import order and real-kernel checks as Notebook 06 R10.
    import paddle

    paddle.set_device("gpu")
    paddle_value = float(paddle.ones([64, 64]).sum().item())
    if paddle_value != 4096.0:
        raise RuntimeError(f"Paddle GPU probe sai: {paddle_value}")

    import torch

    if not torch.cuda.is_available():
        raise RuntimeError("Torch khong thay CUDA tren Modal")
    torch_value = float(torch.ones((64, 64), device="cuda").sum().item())
    if torch_value != 4096.0:
        raise RuntimeError(f"Torch GPU probe sai: {torch_value}")
    paddle_again = float(paddle.ones([32, 32]).sum().item())
    if paddle_again != 1024.0:
        raise RuntimeError(f"Paddle hong sau khi nap Torch: {paddle_again}")
    print(
        f"GPU OK: paddle={paddle.__version__}/{paddle.device.get_device()} "
        f"torch={torch.__version__}/{torch.cuda.get_device_name(0)}"
    )


@app.function(
    image=image,
    gpu=GPU,
    cpu=4.0,
    memory=16384,
    ephemeral_disk=20 * 1024,
    timeout=24 * 60 * 60,
    startup_timeout=30 * 60,
    retries=modal.Retries(initial_delay=10.0, max_retries=2),
    max_containers=1,
    single_use_containers=True,
    volumes={VOLUME_MOUNT: volume},
)
def run_modal_partition(only_videos: list[str] | None = None) -> dict:
    """Process only the validated ``trong/modal`` ZIPs, resumably."""

    os.environ.setdefault("FLAGS_use_mkldnn", "0")
    sys.path.insert(0, str(REMOTE_REPO / "src"))
    volume.reload()
    _probe_dual_gpu()

    import yaml

    from mfe.offline.bundle import BundleLayout, StageStatus, load_shard_plan
    from mfe.offline.fingerprint_gate import (
        FingerprintLockedWriter,
        discover_fingerprint_contract,
    )
    from mfe.offline.stages import STAGES, StageContext, read_keyframes, unload_models
    from mfe.offline.work_partition import load_worker_slice

    raw = yaml.safe_load((REMOTE_REPO / SHARDS).read_text(encoding="utf-8"))
    plan = load_shard_plan(REMOTE_REPO / SHARDS)
    worker_slice = load_worker_slice(
        REMOTE_REPO / WORKERS,
        plan,
        member=MEMBER,
        worker=WORKER,
        expected_shards=SHARDS,
    )
    if set(worker_slice.videos) & set(plan.videos_for("quang")):
        raise RuntimeError("FATAL: Modal partition cham vao video cua Quang")

    selected_zips = set(worker_slice.zip_names)
    my_zips = [pair for pair in plan.zips_for(MEMBER) if pair[0] in selected_zips]
    my_videos = list(worker_slice.videos)
    if only_videos:
        invalid = sorted(set(only_videos) - set(my_videos))
        if invalid:
            raise ValueError(f"Modal smoke/test co video ngoai partition: {invalid}")
        requested = set(only_videos)
        my_videos = [video_id for video_id in my_videos if video_id in requested]
    stages = list(plan.stages)
    if stages != ["n5_ocr_paddle", "n5_ocr_vietocr"]:
        raise RuntimeError(f"stage list sai: {stages}")

    transport = MountedVolumeTransport(VOLUME_MOUNT)
    layout = BundleLayout(plan.bundle)
    work = Path("/tmp/mfe-ocr2")
    zips = Path("/tmp/mfe-ocr2-zips")
    work.mkdir(parents=True, exist_ok=True)
    zips.mkdir(parents=True, exist_ok=True)
    fingerprint = discover_fingerprint_contract(
        transport,
        layout,
        work,
        reference_author=FINGERPRINT_REFERENCE_AUTHOR,
        candidate_videos=plan.videos_for(FINGERPRINT_REFERENCE_AUTHOR),
        required_artifacts=FINGERPRINT_ARTIFACTS,
    )
    for warning in fingerprint.check_environment():
        print(warning)
    print(
        "fingerprint OK: "
        f"{FINGERPRINT_REFERENCE_AUTHOR}/{fingerprint.reference_video} "
        "(env hard-match; model+params locked before upload)"
    )
    writer = FingerprintLockedWriter(
        transport, layout, MEMBER, work, fingerprint=fingerprint
    )
    status = StageStatus.load(transport, layout, MEMBER)

    params = {
        stage: {**raw["params"].get(stage, {}), "device": "gpu", "limit": 0}
        for stage in stages
    }
    keyframe_root = Path(VOLUME_MOUNT) / layout.root.lstrip("/") / "keyframes"
    keyframe_dirs = {
        path.name for path in keyframe_root.iterdir() if path.is_dir()
    } if keyframe_root.is_dir() else set()

    def has_n0_import(video_id: str) -> bool:
        return status.is_done("n0_import_btc", video_id) or video_id in keyframe_dirs

    map_zip = _download(
        raw["extras"]["map_keyframes"],
        zips / "map-keyframes-aic25-b1.zip",
    )
    failures: list[tuple[str, str]] = []
    completed = 0
    images_seen = 0
    started = time.perf_counter()

    print(
        f"Modal worker: {len(my_videos)} video, {len(my_zips)} ZIP, "
        f"author={MEMBER}, worker={WORKER}"
    )
    for zip_name, zip_url in my_zips:
        videos = [
            video_id for video_id in plan.videos_in(zip_name)
            if video_id in set(my_videos) and has_n0_import(video_id)
        ]
        pending = [
            video_id for video_id in videos
            if any(not status.is_done(stage, video_id) for stage in stages)
        ]
        if not pending:
            print(f"{zip_name}: xong het, khong tai")
            continue

        zip_path = _download(zip_url, zips / zip_name, plan.zip_bytes.get(zip_name))
        for video_id in pending:
            try:
                keyframe_dir, image_count = _extract_video(
                    zip_path, video_id, work / "keyframes"
                )
                map_csv = _extract_one_file(
                    map_zip,
                    f"/{video_id}.csv",
                    work / "map-keyframes" / f"{video_id}.csv",
                )
                keyframes = read_keyframes(map_csv, keyframe_dir)
                context = StageContext(
                    video_id, Path("/dev/null"), keyframes, writer, layout, work
                )

                for stage in stages:
                    if status.is_done(stage, video_id):
                        continue
                    context.params = dict(params[stage])
                    marker = STAGES[stage](context)
                    # Update the manifest per stage. If VietOCR fails later, the
                    # Paddle artifact is still represented and resumable.
                    writer.write_part_manifest(
                        video_id, [marker], keyframes=len(keyframes), merge=True
                    )
                    status.done.add((stage, video_id))
                    volume.commit()
                    print(
                        f"{video_id} {stage}: rows={marker['rows']} "
                        f"images={marker['images']} boxes={marker['boxes']} "
                        f"{marker['seconds_per_image']:.2f}s/anh"
                    )

                completed += 1
                images_seen += len(keyframes)
                print(f"{video_id}: xong ({image_count} file)")
            except Exception as err:  # keep the remaining videos moving
                failures.append((video_id, repr(err)))
                print(f"[LOI] {video_id}: {err}")
                traceback.print_exc(limit=3)
                volume.commit()
            finally:
                shutil.rmtree(work / "keyframes" / video_id, ignore_errors=True)
                (work / "map-keyframes" / f"{video_id}.csv").unlink(missing_ok=True)

        zip_path.unlink(missing_ok=True)

    unload_models()
    volume.commit()
    elapsed = time.perf_counter() - started
    left = [
        (stage, video_id)
        for video_id in my_videos
        for stage in stages
        if not status.is_done(stage, video_id)
    ]
    result = {
        "member": MEMBER,
        "worker": WORKER,
        "completed_videos_this_call": completed,
        "images_this_call": images_seen,
        "failures": failures,
        "remaining_tasks": len(left),
        "elapsed_s": round(elapsed, 2),
    }
    print(result)
    return result


@app.local_entrypoint()
def main() -> None:
    """Manual fallback: use ``modal run --detach infra/modal/btc_ocr2.py``."""

    call = run_modal_partition.spawn()
    print(f"Modal OCR2 da spawn: call_id={call.object_id}")
