"""Vietnamese synonyms for the OpenImages label BTC ships — docs/02 §3.

Why this file exists
--------------------
BTC's `objects/*.json` names entities from the OpenImages taxonomy, in English:
`Person`, `Clothing`, `Motorcycle`. BTC asks its questions in Vietnamese (PDF
§1.1). BM25 matches tokens, so between the index and the query there was **no
vocabulary overlap at all** — the text arm could only ever match through
`metadata_text`, which is one string per whole video and therefore scores every
keyframe of that video identically.

Translating the labels is what gives the text arm a **keyframe-level** Vietnamese
signal. That is the difference between BM25 answering "which video" and
answering "which moment", and the second is the question the competition asks.

How the table is meant to be read
---------------------------------
Each English label maps to **several** Vietnamese terms, not one. This is a
retrieval index, not a dictionary: an operator may type "xe máy", "mô tô" or
"xe gắn máy" for the same thing, and BM25 scores a document by which of the
query's tokens it contains. Listing the synonyms in the document is what makes
all three queries hit. The cost is index size, which is negligible here.

Diacritics are kept. `InvertedIndex` normalizes with NFKC + casefold at both
ingest and query time, so "Xe Máy" and "xe máy" already collapse; stripping
tones would additionally collapse "má" and "ma", which loses more than it gains.

Coverage
--------
544 distinct labels appear across the 16-video 2026 sample. The table covers
the wider OpenImages set so that scaling to the full dataset does not need a
second pass. `missing_labels()` reports anything unmapped — run it after any
dataset change rather than trusting this docstring.
"""

