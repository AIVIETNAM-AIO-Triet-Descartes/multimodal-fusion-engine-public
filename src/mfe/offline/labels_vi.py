def translate_labels(labels: list[str]) -> list[str]:
    """Append Vietnamese synonyms to a keyframe's English labels.

    Appends rather than replaces. The English names still carry information —
    a proper noun like "Segway" reads the same in both languages, and keeping
    them means an English query still works — and dropping them would silently
    change what every existing test and every already-built index contains.

    An unmapped label passes through unchanged rather than raising. A detector
    class we have not translated yet should degrade to the status quo (English
    only, matched by nothing) instead of stopping an eight-hour ingest;
    `missing_labels()` is how the gap gets reported.
    """
    out: list[str] = []
    seen: set[str] = set()
    # Deduplicate the incoming labels too, not just the synonyms we add. A term
    # listed twice doubles its BM25 term frequency, scoring the keyframe as if
    # the detector had seen two of the thing.
    for label in labels:
        key = label.casefold()
        if key not in seen:
            seen.add(key)
            out.append(label)
    for label in labels:
        for term in LABELS_VI.get(label, ()):
            key = term.casefold()
            if key not in seen:
                seen.add(key)
                out.append(term)
    return out


def missing_labels(labels: object) -> list[str]:
    """Which of `labels` have no Vietnamese entry. Sorted, deduplicated.

    Run against a real dataset after any change to it — the table is only as
    good as its coverage, and coverage is a fact about the data, not about this
    file's docstring.
    """
    return sorted({str(label) for label in labels if str(label) not in LABELS_VI})
